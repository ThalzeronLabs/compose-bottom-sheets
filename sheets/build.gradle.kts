// Public API guard: the binary-compatibility-validator (BCV) dumps the public API of the release AAR into
// `api/sheets.api`; `apiCheck` (run in CI) fails when the API changes without that file being updated.
// After an intentional API change: `./gradlew :sheets:apiDump` and commit the diff.
//
// The BCV plugin can't be applied directly: AGP 9 compiles Kotlin itself ("built-in Kotlin"), and both BCV and the
// Kotlin plugin's own `abiValidation` only hook into the `kotlin-android` plugin. So its tasks are wired by hand to the
// AAR that AGP builds, which is exactly what consumers compile against.
val bcvRuntime: Configuration by configurations.creating {
    isCanBeConsumed = false
    isCanBeResolved = true
}

val apiClassesJar = tasks.register<Sync>("apiClassesJar") {
    description = "Extracts classes.jar from the release AAR for the API dump."
    into(layout.buildDirectory.dir("bcv/aar"))
}

androidComponents {
    onVariants(selector().withBuildType("release")) { variant ->
        val aar = variant.artifacts.get(SingleArtifact.AAR)
        apiClassesJar.configure {
            from(aar.map { zipTree(it) }) { include("classes.jar") }
        }
    }
}

val apiBuild = tasks.register<KotlinApiBuildTask>("apiBuild") {
    description = "Writes the public API of the release AAR to build/bcv/sheets.api."
    runtimeClasspath.from(bcvRuntime)
    inputJar.set(apiClassesJar.map { layout.buildDirectory.file("bcv/aar/classes.jar").get() })
    outputApiFile.set(layout.buildDirectory.file("bcv/sheets.api"))
    // Generated by the Compose compiler with hashed names that change between compiler versions: not API.
    ignoredClasses.add("com.thalzeronlabs.sheets.ComposableSingletons\$SheetHostKt")
}

tasks.register<KotlinApiCompareTask>("apiCheck") {
    group = "verification"
    description = "Fails if the public API differs from api/sheets.api."
    projectApiFile.set(layout.projectDirectory.file("api/sheets.api"))
    generatedApiFile.set(apiBuild.flatMap { it.outputApiFile })
}

tasks.register<Copy>("apiDump") {
    group = "other"
    description = "Updates api/sheets.api with the current public API."
    from(apiBuild.flatMap { it.outputApiFile })
    into(layout.projectDirectory.dir("api"))
}

tasks.named("check") { dependsOn("apiCheck") }

